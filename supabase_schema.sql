-- In a strict production env, you would issue a custom JWT for each operator
CREATE POLICY "Allow all access for anon" ON mes_operators FOR ALL USING (true);
CREATE POLICY "Allow all access for anon" ON mes_inventory FOR ALL USING (true);
CREATE POLICY "Allow all access for anon" ON mes_production_logs FOR ALL USING (true);
CREATE POLICY "Allow all access for anon" ON mes_financial_ledger FOR ALL USING (true);
CREATE POLICY "Allow all access for anon" ON mes_downtime_logs FOR ALL USING (true);
CREATE POLICY "Allow all access for anon" ON mes_attendance FOR ALL USING (true);
CREATE POLICY "Allow all access for anon" ON mes_loans FOR ALL USING (true);

